"""Validation report: run the whole engine over many synthetic datasets and count what it got right.

`python -m engine.validate` writes docs/VALIDATION.md. Regenerate it after any engine change.
Every number comes from comparing the engine's output with the generator's ground truth, on
messy names, through the same resolve -> reconcile -> score path the product uses.
"""
from collections import Counter
from pathlib import Path

import pandas as pd

from data.generate import generate
from engine.clear import acres_to_clear
from engine.reconcile import YIELD_SIGMAS, reconcile
from engine.replant import REPLANT_ACRE_BAND, REPLANT_SHARE_DROP, replant_signature
from engine.resolve import FUZZY_MIN, resolve
from engine.score import ACRE_TOLERANCE, BUSHEL_TOLERANCE, CONSISTENT, COVERAGE_MIN, INSUFFICIENT, REVIEW, score

VALIDATION_SEEDS = 20  # synthetic datasets per report
REPORT_PATH = Path(__file__).resolve().parent.parent / "docs" / "VALIDATION.md"
LABELS = (CONSISTENT, INSUFFICIENT, REVIEW)
CASES = ("clean", "split_brand", "missing_dealer", "neighbor_dealer", "ghost_seed")


def _rescore_with(rows: pd.DataFrame, extra: pd.Series) -> pd.DataFrame:
    """Score again as if `extra` more licensed acres had been on record."""
    r = rows.copy()
    r["licensed_acres"] = r["licensed_acres"] + extra
    explained = r["licensed_acres"] + r["other_seed_acres"]
    r["acre_gap"] = r["declared_acres"] - explained
    r["max_bushels"] = explained * r["yield_ceiling"]
    r["bushel_gap"] = r["delivered_bushels"] - r["max_bushels"]
    return score(r)


def run(seeds) -> dict:
    labels: Counter = Counter()
    s = Counter()
    for seed in seeds:
        raw = generate(seed=seed)
        resolved = resolve(raw)

        links = raw["record_links"]
        linked = pd.concat([resolved[t][[i, "grower_id"]].rename(columns={i: "record_id"})
                            for t, i in (("acreage_reports", "report_id"), ("elevator_receipts", "receipt_id"))])
        joined = links.merge(linked, on="record_id", how="left", suffixes=("", "_resolved"))
        matched = joined.dropna(subset=["grower_id_resolved"])
        s["owned_records"] += len(joined)
        s["linked"] += len(matched)
        s["wrong_links"] += int((matched["grower_id"] != matched["grower_id_resolved"]).sum())
        ownerless = set(raw["elevator_receipts"]["receipt_id"]) - set(links["record_id"])
        s["non_customer_tickets"] += len(ownerless)
        s["non_customer_linked"] += len(ownerless & set(linked["record_id"]))

        out = replant_signature(score(reconcile(resolved))).merge(
            raw["ground_truth"][["grower_id", "season", "case_type"]], on=["grower_id", "season"])
        labels.update(zip(out["case_type"], out["label"]))

        honest = out["case_type"] != "ghost_seed"
        s["honest"] += int(honest.sum())
        s["false_positives"] += int((honest & (out["label"] == REVIEW)).sum())
        ghost = out[~honest]
        judgeable = ghost[ghost["has_acreage"] & ghost["has_statement"] & (ghost["coverage"] >= COVERAGE_MIN)]
        s["ghost"] += len(ghost)
        s["ghost_judgeable"] += len(judgeable)
        s["ghost_judgeable_flagged"] += int((judgeable["label"] == REVIEW).sum())
        s["replant_on_judgeable_ghost"] += int(judgeable["replant_signal"].sum())
        s["replant_on_honest"] += int(out.loc[honest, "replant_signal"].sum())

        flagged = out[out["label"] != CONSISTENT]
        needed = flagged.apply(acres_to_clear, axis=1)
        s["flagged"] += len(flagged)
        s["cleared_by_stated_acres"] += int((_rescore_with(flagged, needed + 1e-6)["label"] == CONSISTENT).sum())
    return {"seeds": list(seeds), "labels": labels, **s}


def _pct(a: int, b: int) -> str:
    return f"{100 * a / b:.1f}%" if b else "n/a"


def render(r: dict) -> str:
    n = len(r["seeds"])
    rows = "\n".join(
        f"| {case} | " + " | ".join(str(r["labels"][(case, lab)]) for lab in LABELS)
        + f" | {sum(r['labels'][(case, lab)] for lab in LABELS)} |"
        for case in CASES
    )
    return f"""# Validation report

Generated by `python -m engine.validate` over {n} synthetic datasets (seeds {r['seeds'][0]} to {r['seeds'][-1]}),
each with 200 growers over two seasons, with names written the way third parties write them (typos,
"Last, First", initials, "Farms"). Every figure compares the engine's output with the generator's
ground truth, through the same resolve, reconcile, and score path the product runs.

## Headline

- **False positives: {r['false_positives']} of {r['honest']:,}** honest grower-seasons were labeled `review recommended`.
- **Replanting caught: {r['ghost_judgeable_flagged']} of {r['ghost_judgeable']} ({_pct(r['ghost_judgeable_flagged'], r['ghost_judgeable'])})**
  of saved-seed grower-seasons where a conclusion is possible (acreage report linked, seed statement
  on file, dealer coverage at least {COVERAGE_MIN:.0%}). Of all {r['ghost']} saved-seed grower-seasons,
  {_pct(r['ghost_judgeable'], r['ghost'])} met those conditions; the rest are labeled by what was missing, never guessed.
- **Record linking: {r['wrong_links']} wrong links** out of {r['linked']:,} records linked
  ({_pct(r['linked'], r['owned_records'])} of {r['owned_records']:,} customer records linked; the rest wait for an analyst).
  {r['non_customer_linked']} of {r['non_customer_tickets']} elevator tickets from non-customers were linked to anyone.
- **Replant signature:** shown on {r['replant_on_judgeable_ghost']} of {r['ghost_judgeable']} judgeable saved-seed
  grower-seasons and on {r['replant_on_honest']} honest ones. It is context only and never changes a score.
- **What would clear this:** for {r['cleared_by_stated_acres']} of {r['flagged']:,} grower-seasons that were not
  `consistent`, adding exactly the acres the engine names makes the arithmetic consistent.

## Labels by case

| Case | consistent | insufficient data | review recommended | Total |
|---|---|---|---|---|
{rows}

- **clean:** honest; every acre planted with this company's seed.
- **split_brand:** honest; part of the acreage planted with another company's seed.
- **missing_dealer:** honest; part of the seed bought from a dealer in their county that does not report.
- **neighbor_dealer:** honest; the same, but the non-reporting dealer is in a bordering county.
- **ghost_seed:** bought licensed seed one season, then planted saved seed on part of a similar acreage.

Honest growers without a seed statement, or near a non-reporting dealer, land in `insufficient data`
by design: their data cannot rule out an innocent explanation.

## Thresholds

| Setting | Value | Where |
|---|---|---|
| Unsupported share of declared acres treated as noise | {ACRE_TOLERANCE:.0%} | engine/score.py |
| Unsupported share of delivered bushels treated as noise | {BUSHEL_TOLERANCE:.0%} | engine/score.py |
| Dealer coverage needed before a review | {COVERAGE_MIN:.0%} | engine/score.py |
| Yield ceiling | county mean + {YIELD_SIGMAS:g} standard deviations | engine/reconcile.py |
| Fuzzy name match | similarity at least {FUZZY_MIN} | engine/resolve.py |
| Replant signature | explained share falls {REPLANT_SHARE_DROP:.0%}, acreage within {REPLANT_ACRE_BAND:.0%} | engine/replant.py |

## Limits

This is synthetic data written by the same author as the engine, so it tests the logic, not the
world. Real records will contain patterns the generator does not. The next step is a pilot on one
company's historical data with known outcomes.
"""


if __name__ == "__main__":
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(render(run(range(VALIDATION_SEEDS))), encoding="utf-8")
    print(f"wrote {REPORT_PATH}")
